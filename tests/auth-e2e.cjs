// Test navigateur : inscription, déconnexion, connexion, changement de pseudo via le serveur.
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const BASE = process.env.BASE || 'http://localhost:8080';
const stub = fs.readFileSync(path.join(__dirname, 'three-stub.js'), 'utf8');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let bad = 0; const ok = (c, m) => { console.log((c ? '  ✓ ' : '  ✗ ') + m); if (!c) bad++; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext();
  await ctx.route('**/*', (r) => { const u = r.request().url();
    if (u.startsWith(BASE)) return r.continue();
    if (u.includes('three.min.js')) return r.fulfill({ contentType: 'application/javascript', body: stub });
    if (u.includes('tailwindcss')) return r.fulfill({ contentType: 'application/javascript', body: '' });
    if (u.includes('fonts.googleapis')) return r.fulfill({ contentType: 'text/css', body: '' });
    return r.abort(); });
  const page = await ctx.newPage();
  page.on('pageerror', (e) => { console.log('  ✗ pageerror ' + e.message); bad++; });
  await page.goto(BASE + '/', { waitUntil: 'domcontentloaded' }); await sleep(800);
  const name = 'Test' + Date.now() % 100000;
  const reg = await page.evaluate((n) => gatewayAction({ action: 'register', username: n, password: 'secret1', avatar: '🦊' }), name);
  ok(reg.ok && reg.token, 'inscription acceptée, jeton reçu');
  ok(!JSON.stringify(reg).includes('secret1') && !(reg.row && reg.row.password), 'aucun mot de passe renvoyé');
  const bad1 = await page.evaluate((n) => gatewayAction({ action: 'login', username: n, password: 'faux' }), name);
  ok(!bad1.ok, 'mauvais mot de passe refusé');
  const good = await page.evaluate((n) => gatewayAction({ action: 'login', username: n, password: 'secret1' }), name);
  ok(good.ok && good.token, 'connexion avec le bon mot de passe');
  await page.evaluate((t) => setAuthToken(t), good.token);
  const list = await page.evaluate(async () => { const r = await supabaseFetch('accounts?select=*'); return r.ok ? JSON.stringify(await r.json()) : 'ERR' + r.status; });
  ok(!/secret1|"password":"[^"]/.test(list), 'la liste des comptes ne montre aucun mot de passe');
  const rn = await page.evaluate((n) => gatewayAction({ action: 'rename', newName: n + 'X' }), name);
  ok(rn.ok && rn.token, 'changement de pseudo accepté');
  const hack = await page.evaluate(async () => { setAuthToken(''); const r = await supabaseFetch('accounts?username=eq.YSTROZ', { method: 'PATCH', body: JSON.stringify({ balance: 999999999 }) }); return r.status; });
  ok([401, 403, 405].includes(hack), 'modifier un solde sans connexion est refusé (' + hack + ')');
  await b.close();
  console.log(bad ? bad + ' erreur(s)' : 'Tout est bon');
  process.exit(bad ? 1 : 0);
})();
